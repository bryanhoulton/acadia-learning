# Build auth headers if credentials are provided
OTEL_AUTH_HEADERS: dict[str, str] | None = None
if OTEL_EXPORTER_OTLP_USERNAME and OTEL_EXPORTER_OTLP_PASSWORD:
    credentials = f"{OTEL_EXPORTER_OTLP_USERNAME}:{OTEL_EXPORTER_OTLP_PASSWORD}"
    encoded = base64.b64encode(credentials.encode()).decode()
    OTEL_AUTH_HEADERS = {"Authorization": f"Basic {encoded}"}


def OTEL_PROVIDER_SETUP() -> None:
    if not OTEL_EXPORTER_OTLP_ENDPOINT:
        return

    current_tracer_provider = trace.get_tracer_provider()
    if isinstance(current_tracer_provider, TracerProvider):
        return  # Already initialized

    resource = Resource.create(
        {
            "service.name": OTEL_SERVICE_NAME,
            "deployment.environment": OTEL_ENVIRONMENT,
        }
    )

    # Set up Traces
    tracer_provider = TracerProvider(resource=resource)
    traces_endpoint = f"{OTEL_EXPORTER_OTLP_ENDPOINT}/v1/traces"
    span_exporter = OTLPSpanExporter(endpoint=traces_endpoint, headers=OTEL_AUTH_HEADERS)
    tracer_provider.add_span_processor(BatchSpanProcessor(span_exporter))

    trace.set_tracer_provider(tracer_provider)

    # Set up Logs
    logger_provider = LoggerProvider(resource=resource)
    logs_endpoint = f"{OTEL_EXPORTER_OTLP_ENDPOINT}/v1/logs"
    log_exporter = OTLPLogExporter(endpoint=logs_endpoint, headers=OTEL_AUTH_HEADERS)
    logger_provider.add_log_record_processor(BatchLogRecordProcessor(log_exporter))
    set_logger_provider(logger_provider)

    # Attach OTEL handler to root logger to capture all logs
    otel_handler = LoggingHandler(level=logging.INFO, logger_provider=logger_provider)
    logging.getLogger().addHandler(otel_handler)


if OTEL_EXPORTER_OTLP_ENDPOINT:
    OTEL_PROVIDER_SETUP()
